export type SuggestedEquipmentKey = (typeof SUGGESTED_EQUIPMENT_KEYS)[number];
export type SuggestedMaterialsKey = (typeof SUGGESTED_MATERIALS_KEYS)[number];
export type EstimatedDurationHintKey =
  (typeof ESTIMATED_DURATION_HINT_KEYS)[number];

const EQUIPMENT_SET = new Set<string>(SUGGESTED_EQUIPMENT_KEYS);
const MATERIALS_SET = new Set<string>(SUGGESTED_MATERIALS_KEYS);
const DURATION_SET = new Set<string>(ESTIMATED_DURATION_HINT_KEYS);

export function isValidEquipmentKey(key: string): key is SuggestedEquipmentKey {
  return EQUIPMENT_SET.has(key);
}

export function isValidMaterialsKey(key: string): key is SuggestedMaterialsKey {
  return MATERIALS_SET.has(key);
}

export function isValidDurationHintKey(
  key: string
): key is EstimatedDurationHintKey {
  return DURATION_SET.has(key);
}

/** Filter array to only allowed equipment keys. */
export function filterAllowedEquipment(keys: string[]): SuggestedEquipmentKey[] {
  return keys.filter(isValidEquipmentKey);
}

/** Filter array to only allowed materials keys. */
export function filterAllowedMaterials(keys: string[]): SuggestedMaterialsKey[] {
  return keys.filter(isValidMaterialsKey);
}

/** Validate and return duration hint or null. */
export function parseDurationHint(
  key: string | null | undefined
): EstimatedDurationHintKey | null {
  if (key == null || !DURATION_SET.has(key)) return null;
  return key as EstimatedDurationHintKey;
}
